#!/usr/bin/env python3
"""Writes the application resources of the air/OS build (an rdef for rc):
the signature, single launch (a second launch hands its arguments to the
running msga), the version from version.cmake and the vector icon
(resources/haiku/msga.hvif, made from gfx/icon.svg by svg2hvif.py).

    python3 tools/haiku/make-rdef.py OUT.rdef [PACKAGE_REVISION]
"""
import os
import re
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))


def main():
    out = sys.argv[1]
    version = int(re.search(r'MSGA_VERSION\s+(\d+)', open(os.path.join(ROOT, 'version.cmake')).read()).group(1))
    icon = open(os.path.join(ROOT, 'resources/haiku/msga.hvif'), 'rb').read().hex()
    rows = '\n'.join('\t$"%s"' % icon[i:i + 64] for i in range(0, len(icon), 64))
    open(out, 'w').write('''// Generated by tools/haiku/make-rdef.py: edit that, not this.
resource app_signature "application/x-vnd.airos-msga";

resource app_flags B_SINGLE_LAUNCH;

resource app_version {
	major  = %(v)d,
	middle = 0,
	minor  = 0,
	variety = B_APPV_FINAL,
	internal = 0,
	short_info = "MSGA %(v)d",
	long_info = "MSGA %(v)d, a native Slack client (make-slack-great-again) for air/OS"
};

resource file_types message {
	"types" = "application/x-vnd.Be.URL.msga"
};

resource vector_icon array {
%(rows)s
};
''' % {'v': version, 'rows': rows})


if __name__ == '__main__':
    main()
